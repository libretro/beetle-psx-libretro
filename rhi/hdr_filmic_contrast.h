/*
===========================================================================

Filmic's contrast ladder.

Sobotka authored seven of these and Blender ships them all, named from
Very Low to Very High.  They are not a parameter on one curve - each is
its own authored lookup, which is why this is a table per setting rather
than a spline with a knob on it.

Blender applies a variant as a look on top of the base view transform,
so its config lists the variant followed by the base's inverse.  This
pipeline applies one lookup directly, so selecting a variant here gives
the same result with one fewer stage.

Taken from Blender (GNU GPL),
release/datafiles/colormanagement/filmic/, as the base curve was.

  Filmic Dynamic Range LUT crafted by Troy James Sobotka.

Each original is 4096 entries; these are 256, reproducing them to
0.000164 - comfortably under one 8-bit step.  Indexed by the log-encoded
value, exactly as the base curve is.

The low end is what separates them, and it is what makes this worth
having in a game this dark.  At a scene value of 0.002 - the sort of dim
specular a distant emergency light leaves on wet metal - Very Low
returns 0.0078 where Very High returns 0.00001.

===========================================================================
*/

