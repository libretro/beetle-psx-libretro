/* ---- Analog signal path FIR tables -------------------------------------
 * Designed at the PSX CRTC base clock: NTSC 15*fsc (53.6932 MHz), PAL 12*fsc
 * (53.2034 MHz). Both ratios are exact, so framebuffer -> signal is an integer
 * zero-order hold and nothing is resampled on the way in.
 *
 * Three luma bandwidths, because the cable tiers are not limited by the same
 * thing:
 *
 *   AN_LUMA_WIDE  S-Video. Luma has its own wire and no chroma to dodge, so it
 *                 carries the ~6 MHz the handbook allows a baseband signal.
 *   AN_LUMA       Composite. Luma shares the wire with a subcarrier that has to
 *                 be separated back out, which is what caps it - 4.2 MHz on
 *                 NTSC, 5 MHz on PAL-B where the subcarrier sits higher.
 *   AN_LUMA_RF    RF. The modulator and channel are the limit, and consumer
 *                 game modulators were poor: ~3 MHz.
 *
 * Chroma is a 3x box cascade rather than a designed FIR - the handbook calls
 * for a gaussian here specifically to avoid ringing, and a sharp filter rings
 * badly at this bandwidth. AN_BANDPASS extracts the comb chroma estimate.
 *
 * Region is selected by -DPAL. Regenerated by tools/analog_filters.py. */
