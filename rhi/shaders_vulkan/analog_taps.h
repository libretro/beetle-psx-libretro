/* ---- Analog signal path FIR tables -------------------------------------
 * Designed at the PSX CRTC base clock: NTSC 15*fsc (53.6932 MHz), PAL 12*fsc
 * (53.2034 MHz). Both ratios are exact, so framebuffer -> signal is an integer
 * zero-order hold and nothing is resampled on the way in.
 *
 * Stored as PREFIX SUMS, not taps. The encode's input is piecewise constant
 * over `div` base samples - that is what the CRTC hold is - so every run of
 * filter taps landing on the same native pixel can be collapsed into one
 * weighted fetch, the weight being a difference of two prefix entries. That
 * turns a 95-tap convolution into 11-25 texture reads depending on the dot
 * clock, with identical arithmetic.
 *
 * Three luma bandwidths, because the cable tiers are not limited by the same
 * thing:
 *   AN_LUMA_WIDE  S-Video, ~6 MHz - luma has its own wire
 *   AN_LUMA       Composite, 4.2 MHz NTSC / 5 MHz PAL-B - capped by sharing
 *                 the wire with a subcarrier that must be separated back out
 *   AN_LUMA_RF    RF, ~3 MHz - the modulator is the limit
 *
 * Chroma is a 3x box cascade rather than a designed FIR: the handbook calls for
 * a gaussian to avoid ringing, and a sharp filter rings badly at this width.
 *
 * There is deliberately no chroma band-pass. Demodulating the comb estimate
 * directly and rebuilding the carrier from the recovered I/Q is both cheaper
 * (31 taps instead of 95) and measurably more accurate, because the
 * demodulator's low-pass is a matched band-pass centred exactly on fsc.
 *
 * Region selected by -DPAL. Regenerated by tools/analog_filters.py. */
